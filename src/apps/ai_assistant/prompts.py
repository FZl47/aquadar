def build_user_prompt(experiment):
    description = experiment.description or 'ندارد'
    return (
        f'نام آزمایش: {experiment.name}\n'
        f'تاریخ آزمایش (میلادی): {experiment.date.isoformat()}\n'
        f'توضیحات ثبت‌کننده: {description}\n\n'
        'فایل‌های آزمایش خاک، برگ و آب در ادامه پیوست شده‌اند. آنها را تحلیل کنید و خروجی JSON را بدهید.'
    )
